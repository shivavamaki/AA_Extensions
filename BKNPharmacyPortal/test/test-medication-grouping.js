"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const path = require("node:path");
const source = fs.readFileSync(path.join(__dirname, "../src/features/home-med/page-home-med.js"), "utf8");
const fn = source.match(/function _medicationDisplayGroup\(med\) \{[\s\S]*?\n\}/)[0];
const box = {};
vm.runInNewContext(fn, box);
const rank = box._medicationDisplayGroup;
assert.equal(rank({takeUntilFinished:true, source:"pom"}), 0);
assert.equal(rank({continuity:"continued"}), 1);
assert.equal(rank({continuity:"new"}), 2);
assert.equal(rank({continuity:"adjusted"}), 3);
assert.equal(rank({continuity:""}), 4);
assert.equal(rank({}), 4);
assert.equal(rank({continuity:"pom"}), 5);
assert.equal(rank({source:"pom",continuity:"continued"}), 5);
assert.equal(rank({source:"own"}), 5);
console.log("Medication grouping regression checks passed.");