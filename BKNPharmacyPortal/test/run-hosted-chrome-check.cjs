const fs=require('fs');
(async()=>{
 const pages=await (await fetch('http://127.0.0.1:9227/json')).json();
 const ws=new WebSocket(pages[0].webSocketDebuggerUrl);await new Promise(r=>ws.onopen=r);
 let id=0;const pending=new Map(),errors=[];
 ws.onmessage=e=>{const m=JSON.parse(e.data);if(m.id){const p=pending.get(m.id);pending.delete(m.id);m.error?p.reject(m.error):p.resolve(m.result)}else if(m.method==='Runtime.exceptionThrown')errors.push(m.params.exceptionDetails.text+': '+(m.params.exceptionDetails.exception?.description||''));};
 const call=(method,params={})=>new Promise((resolve,reject)=>{pending.set(++id,{resolve,reject});ws.send(JSON.stringify({id,method,params}))});
 const evalJS=async(expression)=>{const r=await call('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true});if(r.exceptionDetails)throw new Error(JSON.stringify(r.exceptionDetails));return r.result.value;};
 await call('Runtime.enable');await call('Page.enable');
 await call('Page.navigate',{url:process.env.HM_TEST_URL});
 await new Promise(r=>setTimeout(r,2500));
 await evalJS(`document.querySelector('form input[name=username]').value='test';document.querySelector('form input[name=password]').value='test';document.querySelector('form').requestSubmit();`);
 await new Promise(r=>setTimeout(r,5000));
 console.log(JSON.stringify({errors,debug:await evalJS('window.__HM_HOSTED_DEBUG__'),rows:await evalJS("document.querySelectorAll('.a4-preview tr.med-row').length"),status:await evalJS("document.querySelector('[role=status]').textContent")}));
 await evalJS(`const q=document.querySelector('.a4-preview .qty-main');q.focus();q.textContent='99 Tablet';q.dispatchEvent(new Event('blur'));q.blur();`);
 await new Promise(r=>setTimeout(r,2000));
 const saved=await evalJS("document.querySelector('[role=status]').textContent");
 if(saved!=='Saved.')console.log(await evalJS('JSON.stringify({med:_meds[0],context:_context,editable:document.querySelector(".a4-preview .qty-main")?.outerHTML})'));
 if(saved!=='Saved.')throw new Error('Quantity edit not saved: '+saved);
 await call('Page.reload');await new Promise(r=>setTimeout(r,2000));
 await evalJS(`document.querySelector('form input[name=username]').value='test';document.querySelector('form input[name=password]').value='test';document.querySelector('form').requestSubmit();`);
 await new Promise(r=>setTimeout(r,4000));
 const qty=await evalJS("document.querySelector('.a4-preview .qty-main').textContent");
 if(!qty.includes('99'))throw new Error('Saved quantity missing on reload: '+qty);
 if(errors.length)throw new Error(errors.join('\n'));
 const previewPages=await evalJS("document.querySelectorAll('.a4-page').length");
 console.log(JSON.stringify({saved,reloadedQuantity:qty,previewPages,errors}));
 fs.mkdirSync('reports',{recursive:true});
 const shot=await call('Page.captureScreenshot',{format:'png'});fs.writeFileSync('reports/hm-hosted-synthetic-browser.png',Buffer.from(shot.data,'base64'));
 const pdf=await call('Page.printToPDF',{preferCSSPageSize:true,printBackground:true});fs.writeFileSync('reports/hm-hosted-synthetic-browser.pdf',Buffer.from(pdf.data,'base64'));
 const pdfPages=[...Buffer.from(pdf.data,'base64').toString('latin1').matchAll(/\/Type\s*\/Page\b/g)].length;
 if(pdfPages!==previewPages)throw new Error('PDF/preview page count differs');
 console.log('PASS: PDF pages match preview: '+pdfPages);
 ws.close();
})().catch(e=>{console.error(e);process.exit(1)});
